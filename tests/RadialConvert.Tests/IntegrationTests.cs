using System;
using System.IO;
using System.Linq;
using System.Threading;
using System.Threading.Tasks;
using DocumentFormat.OpenXml.Packaging;
using RadialConvert.Conversion;
using Xunit;
using Xunit.Abstractions;

namespace RadialConvert.Tests;

/// <summary>
/// Runs real conversions through the external tools. Each test returns early (and logs why) when its tool
/// is not installed, so the suite still passes on a clean machine.
/// </summary>
public sealed class IntegrationTests : IDisposable
{
    private readonly ITestOutputHelper _log;
    private readonly string _dir = Directory.CreateTempSubdirectory("radialconvert-it-").FullName;

    public IntegrationTests(ITestOutputHelper log) => _log = log;

    public void Dispose() => Directory.Delete(_dir, recursive: true);

    private static ConversionOption Opt(string id) => ConversionRegistry.All.First(o => o.Id == id);

    private bool Has(Tool tool)
    {
        if (ToolLocator.Find(tool) != null) return true;
        _log.WriteLine($"SKIPPED: {tool} not installed.");
        return false;
    }

    private Task<string> Convert(string source, string id) =>
        ConversionService.RunAsync(source, Opt(id), CancellationToken.None);

    /// <summary>Two-page PDF with real text, generated by ImageMagick from a text file.</summary>
    private async Task<string> MakeTextPdf()
    {
        var pdf = Path.Combine(_dir, "sample.pdf");
        var magick = ToolLocator.Require(Tool.ImageMagick);
        await ProcessRunner.RunAsync(magick, new[]
        {
            "-size", "850x1100", "xc:white", "-pointsize", "40", "-draw", "text 80,120 'Page one'",
            "(", "-size", "850x1100", "xc:white", "-pointsize", "40", "-draw", "text 80,120 'Page two'", ")",
            pdf
        }, CancellationToken.None);
        return pdf;
    }

    [Fact]
    public async Task PngToJpgAndNumbering()
    {
        if (!Has(Tool.ImageMagick)) return;
        var png = Path.Combine(_dir, "pic.png");
        await ProcessRunner.RunAsync(ToolLocator.Require(Tool.ImageMagick), new[] { "-size", "40x30", "xc:red", png }, CancellationToken.None);

        Assert.Equal(Path.Combine(_dir, "pic.jpg"), await Convert(png, "image.jpg"));
        Assert.Equal(Path.Combine(_dir, "pic (1).jpg"), await Convert(png, "image.jpg"));
    }

    [Fact]
    public async Task PdfToPowerPointHasOneSlidePerPage()
    {
        if (!Has(Tool.ImageMagick) || !Has(Tool.Poppler)) return;
        var result = await Convert(await MakeTextPdf(), "pdf.pptx");

        using var doc = PresentationDocument.Open(result, false);
        Assert.Equal(2, doc.PresentationPart!.SlideParts.Count());
    }

    [Fact]
    public async Task MultiPagePdfToPngCreatesFolder()
    {
        if (!Has(Tool.ImageMagick) || !Has(Tool.Poppler)) return;
        var result = await Convert(await MakeTextPdf(), "pdf.png");

        Assert.True(Directory.Exists(result));
        Assert.Equal(new[] { "sample - page 1.png", "sample - page 2.png" },
            Directory.GetFiles(result).Select(Path.GetFileName).OrderBy(n => n).ToArray());
        Assert.False(File.Exists(Path.Combine(_dir, "sample.png"))); // placeholder removed
    }

    [Fact]
    public async Task PdfToWordProducesDocx()
    {
        if (!Has(Tool.ImageMagick) || !Has(Tool.Pdf2Docx)) return;
        var result = await Convert(await MakeTextPdf(), "pdf.word");

        using var doc = WordprocessingDocument.Open(result, false);
        Assert.NotNull(doc.MainDocumentPart?.Document.Body);
    }

    [Fact]
    public async Task MarkdownToHtmlAndDocx()
    {
        if (!Has(Tool.Pandoc)) return;
        var md = Path.Combine(_dir, "notes.md");
        await File.WriteAllTextAsync(md, "# Title\n\nSome **bold** text.\n");

        var html = await File.ReadAllTextAsync(await Convert(md, "doc.html"));
        Assert.Contains("<strong>bold</strong>", html);

        using var doc = WordprocessingDocument.Open(await Convert(md, "doc.docx"), false);
        Assert.Contains("Title", doc.MainDocumentPart!.Document.Body!.InnerText);
    }

    [Fact]
    public async Task DocxToPdfWithLibreOffice()
    {
        if (!Has(Tool.Pandoc) || !Has(Tool.LibreOffice)) return;
        var md = Path.Combine(_dir, "letter.md");
        await File.WriteAllTextAsync(md, "Hello from RadialConvert.\n");
        var docx = await Convert(md, "doc.docx");

        var pdf = await Convert(docx, "office.pdf");
        Assert.StartsWith("%PDF", await File.ReadAllTextAsync(pdf).ContinueWith(t => t.Result[..4]));
    }

    [Fact]
    public async Task MissingSourceGivesFriendlyError()
    {
        var ex = await Assert.ThrowsAsync<ConversionException>(() => Convert(Path.Combine(_dir, "gone.png"), "image.jpg"));
        Assert.Contains("no longer exists", ex.Message);
    }
}
